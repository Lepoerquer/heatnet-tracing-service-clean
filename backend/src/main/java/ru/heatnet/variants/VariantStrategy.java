package ru.heatnet.variants;

/**
 * M7. Опорные стратегии построения содержательно различающихся вариантов.
 *
 * <p>Обновлённое приложение §6: «В каждом режиме сервис может вернуть до трёх содержательно
 * отличающихся вариантов. Небольшое смещение одной и той же трассы отдельным вариантом не
 * считается». ТЗ «2. ДИТ» §2.8 перечисляет, что делает вариант отличающимся: точка врезки,
 * объединение ОКС в общую сеть, маршрут, разделение на несколько отдельных частей новой сети,
 * способ прохождения ограничения.</p>
 *
 * <p>Каждая стратегия выражается через уже существующий публичный контракт M4
 * {@code NetworkPlanner.plan(ingest, existing, geometry, oksPoints)} — меняется только состав
 * прогонов. Код M2/M3/M4 при этом не трогается.</p>
 */
public enum VariantStrategy {

    /** A. Все точки подключения одним прогоном: планировщик сам выбирает совместно/раздельно по ΔS. */
    JOINT_ALL("A", "все ОКС одним прогоном (выбор совместно/раздельно по ΔS)"),

    /**
     * B. Каждая точка подключения — отдельная часть сети со своей врезкой (без совместных участков).
     * Если отдельный ввод для ОКС невозможен (подходы перекрыты другими вводами), допускается
     * ответвление от уже построенной части — чтобы не оставлять ОКС неподключённым (Разъяснение №15).
     */
    SEPARATE_EACH("B", "каждый ОКС своей врезкой, где это возможно (иначе — ответвление)"),

    /** C. Точки подключения разбиты на две географические группы; совместные участки — только внутри группы. */
    CLUSTERED("C", "ОКС разбиты на группы, совместное подключение только внутри группы");

    private final String code;
    private final String description;

    VariantStrategy(String code, String description) {
        this.code = code;
        this.description = description;
    }

    /** Короткий код стратегии — попадает в {@code variant_id}. */
    public String getCode() {
        return code;
    }

    public String getDescription() {
        return description;
    }
}

package ru.heatnet.network;

/**
 * AUDIT-24.09 (Claude). Режим построения плана в одном сеансе дерева Штейнера (M4 → M7).
 *
 * <ul>
 *   <li>{@link #JOINT} — любой ОКС может присоединиться к уже построенной новой сети (совместное
 *       подключение, §2.3 ТЗ).</li>
 *   <li>{@link #SEPARATE} — каждый ОКС отдельной частью сети со своей точкой врезки
 *       («разделение на несколько отдельных частей», §2.8 ТЗ).</li>
 *   <li>{@link #CLUSTERED} — совместное подключение только внутри группы ОКС.</li>
 * </ul>
 * Все режимы строятся в одном общем графе и с общей проверкой пересечений, поэтому части сети
 * разных групп не пересекаются между собой (раньше раздельные прогоны сливались постфактум
 * и вариант отбраковывался из-за пересечений).
 */
public enum PlanMode {
    JOINT,
    SEPARATE,
    CLUSTERED
}

package ru.heatnet.calc.model;

/** Тип узла дерева новой сети. */
public enum NodeKind {
    /** Точка врезки в существующую сеть — корень дерева. */
    TIE_IN,
    /** Новая тепловая камера (точка разветвления). */
    NEW_CHAMBER,
    /** Технический узел: смена DN, способа прокладки, коэффициента, глубины. */
    TECHNICAL_NODE,
    /** Точка подключения перспективного ОКС — лист дерева. */
    OKS_CONNECTION
}
